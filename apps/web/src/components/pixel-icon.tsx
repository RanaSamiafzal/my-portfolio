import { cn } from "@repo/ui";

// 8×8 pixel-art glyphs ("#" = lit).
const ICONS = {
  stack: ["...##...", "..####..", ".######.", "..####..", "...##...", ".#.##.#.", "..####..", "...##..."],
  bolt: ["....###.", "...###..", "..###...", ".######.", "...###..", "..###...", ".###....", ".##....."],
  shield: [".######.", "##....##", "##.##.##", "##.##.##", "##....##", ".##..##.", "..####..", "...##..."],
  code: ["........", "..#..#..", ".#....#.", "#..##..#", "#..##..#", ".#....#.", "..#..#..", "........"],
  rocket: ["...##...", "..####..", "..#..#..", "..####..", ".######.", "##.##.##", "...##...", "..#..#.."],
  chart: ["......##", "......##", "....####", "....####", "..######", "..######", "########", "########"],
  users: ["..##....", ".####.##", ".####.##", "..##.###", ".#####..", "########", "########", "........"],
  clock: ["..####..", ".#....#.", "#...#..#", "#...#..#", "#..##..#", "#......#", ".#....#.", "..####.."],
} as const;

export type PixelIconName = keyof typeof ICONS;

export function PixelIcon({ name, className }: { name: PixelIconName; className?: string }) {
  const grid = ICONS[name];
  return (
    <svg viewBox="0 0 8 8" className={cn("size-5 drop-shadow-[0_0_6px_rgba(0,255,65,0.6)]", className)} shapeRendering="crispEdges" aria-hidden>
      {grid.flatMap((row, y) =>
        [...row].map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill="#00ff41" /> : null)),
      )}
    </svg>
  );
}
